/**
 * 环形相邻计数
 * 规则：
 *   1. 找最大值 max 和最小值 min，定义"相邻值" = max - min
 *   2. 将数值序列视为环形（首尾相接：最后一个→第一个 也是相邻）
 *   3. 对每对相邻计算 |a[i] - a[i+1]|
 *   4. 若差绝对值 == 1 或 == 相邻值(max-min)，则计数 +1
 *   5. 返回总计数
 */
function 环形相邻计数(vals) {
    if (!vals || vals.length < 2) return 0;

    // 找最大值和最小值
    let vMin = vals[0], vMax = vals[0];
    for (let i = 0; i < vals.length; i++) {
        if (vals[i] < vMin) vMin = vals[i];
        if (vals[i] > vMax) vMax = vals[i];
    }
    const diff = vMax - vMin;  // 相邻值

    // 边界：所有值相同（diff=0），没有"相邻"关系，返回 0
    if (diff === 0) return 0;

    // 环形遍历，统计满足条件的相邻对
    let count = 0;
    const n = vals.length;
    for (let i = 0; i < n; i++) {
        const a = vals[i];
        const b = vals[(i + 1) % n];  // 环形：最后一个→第一个
        const d = Math.abs(a - b);
        if (d === 1 || d === diff) {
            count++;
        }
    }
    return count;
}

