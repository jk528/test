// 二、测试框架
// ============================================================

let passCount = 0, failCount = 0;
const results = [];

function 断言_相等(实际, 期望, 用例名, 输入) {
    const 通过 = 实际 === 期望;
    const 状态 = 通过 ? 'PASS' : 'FAIL';
    if (通过) passCount++; else failCount++;
    results.push({ 用例名, 输入, 期望, 实际, 通过 });
    console.log(`[${状态}] ${用例名}: 输入=[${输入}] 期望=${期望} 实际=${实际}`);
}

