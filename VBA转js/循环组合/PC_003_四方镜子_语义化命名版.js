//  主入口
// -------------------------------------------------------------

function 四方镜子_主入口() {
    var 选择 = 弹出输入框(
        "请选择操作：\n" +
        "1: 四方循环_合并_竖\n" +
        "2: 四方循环_合并_横\n" +
        "3: 四方循环_分_竖\n" +
        "4: 四方循环_分_横\n" +
        "5: 双边循环_合并_竖\n" +
        "6: 双边循环_合并_横\n" +
        "7: 双边循环_分_竖\n" +
        "8: 双边循环_分_横",
        "四方镜子", "1", 1
    );
    if (选择 === false || 选择 === null) return;
    选择 = parseInt(选择);

    switch (选择) {
        case 1: 四方镜子_合并_竖(); break;
        case 2: 四方镜子_合并_横(); break;
        case 3: 四方镜子_分开_竖(); break;
        case 4: 四方镜子_分开_横(); break;
        case 5: 四方镜子_双边循环_合并_竖(); break;
        case 6: 四方镜子_双边循环_合并_横(); break;
        case 7: 四方镜子_双边循环_分_竖(); break;
        case 8: 四方镜子_双边循环_分_横(); break;
        default: 弹窗提示("无效选择", 48);
    }
}
