function 计算最小公倍数(数组) {
    return Application.WorksheetFunction.Lcm(数组);
}

function 计算数组乘积(数组) {
    var 乘积 = 1;
    for (var i = 0; i < 数组.length; i++) 乘积 *= 数组[i];
    return 乘积;
}

/**
 * 构建双边循环矩阵（列优先存储：结果[列][行]）
 * 每列独立循环，总行数 = LCM(各列行数)
 */
function 构建LCM循环矩阵(源数据, 每列元素个数, 结果行数) {
    var 列数 = 每列元素个数.length;
    var 结果 = [];

    for (var 列索引 = 0; 列索引 < 列数; 列索引++) {
        结果[列索引] = [];
        var 周期长度 = 每列元素个数[列索引];

        for (var 行索引 = 0; 行索引 < 结果行数; 行索引++) {
            var 源行号 = 循环索引(行索引 + 1, 周期长度);
            结果[列索引][行索引] = 源数据[源行号 - 1][列索引];
        }
    }
    return 结果;
}

