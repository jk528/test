function 获取最后一列(工作表) {
    try {
        return 工作表.Cells(1, 工作表.Columns.Count).End(-4159).Column;  // xlToLeft
    } catch (e) {
        return 工作表.UsedRange.Columns.Count;
    }
}

function 获取最后一行(工作表, 列号) {
    try {
        return 工作表.Cells(工作表.Rows.Count, 列号).End(-4162).Row;  // xlUp
    } catch (e) {
        return 工作表.UsedRange.Rows.Count;
    }
}

function 批量读取区域(工作表, 起始行, 起始列, 结束行, 结束列) {
    return 工作表.Range(工作表.Cells(起始行, 起始列), 工作表.Cells(结束行, 结束列)).Value2;
}

