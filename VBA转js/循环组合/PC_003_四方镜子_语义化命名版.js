function 四方镜子_合并_竖() {
    var 连接符 = 弹出输入框("请输入连接符号:", "连接符号", "-", 2);
    if (连接符 === null) return;
    当前连接符号 = 连接符 || "-";
    执行四方循环(false, false);   // 反向 + 竖向
}

function 四方镜子_合并_横() {
    var 连接符 = 弹出输入框("请输入连接符号:", "连接符号", "-", 2);
    if (连接符 === null) return;
    当前连接符号 = 连接符 || "-";
    执行四方循环(true, true);     // 正向 + 横向
}

function 四方镜子_分开_竖() {
    当前连接符号 = "";
    执行四方循环(false, false);
}

function 四方镜子_分开_横() {
    当前连接符号 = "";
    执行四方循环(true, true);
}

function 四方镜子_双边循环_合并_竖() {
    var 连接符 = 弹出输入框("请输入连接符号:", "连接符号", "-", 2);
    if (连接符 === null) return;
    当前连接符号 = 连接符 || "-";
    执行双边循环(true);
}

function 四方镜子_双边循环_合并_横() {
    var 连接符 = 弹出输入框("请输入连接符号:", "连接符号", "-", 2);
    if (连接符 === null) return;
    当前连接符号 = 连接符 || "-";
    执行双边循环(false);
}

function 四方镜子_双边循环_分_竖() {
    当前连接符号 = "";
    执行双边循环(true);
}

function 四方镜子_双边循环_分_横() {
    当前连接符号 = "";
    执行双边循环(false);
}

