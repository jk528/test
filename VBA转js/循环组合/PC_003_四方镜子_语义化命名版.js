/**
 * 循环索引：把任意正整数映射到 [1, 周期长度] 的循环范围内
 * 就像钟表：第1格=1，第12格=12，第13格=1
 * 等价于 ((序号 + 周期长度 - 1) % 周期长度) + 1
 */
function 循环索引(序号, 周期长度) {
    return ((序号 + 周期长度 - 1) % 周期长度) + 1;
}

/**
 * 向上取整除法：ceil(被除数 / 除数)
 * 用于计算"第几个周期"
 */
function 向上取整除法(被除数, 除数) {
    return Math.ceil(被除数 / 除数);
}

