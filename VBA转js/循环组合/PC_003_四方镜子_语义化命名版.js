//  核心算法组：四方循环（笛卡尔积）
// -------------------------------------------------------------

/**
 * 计算每列的循环步长
 * 步长含义：该列经过多少行才变化一次
 *
 * 正向循环（左列慢，右列快）：
 *   第1列步长 = 1（每行都变）
 *   第n列步长 = 前一列步长 × 前一列元素个数
 *
 * 反向循环（左列快，右列慢）：
 *   第n列步长 = 总行数 / 前n列元素个数的乘积
 */
function 计算循环步长数组(每列元素个数, 是否正向) {
    var 列数 = 每列元素个数.length;
    var 步长数组 = [];

    if (是否正向) {
        步长数组[0] = 1;
        for (var 列索引 = 1; 列索引 < 列数; 列索引++) {
            步长数组[列索引] = 步长数组[列索引 - 1] * 每列元素个数[列索引 - 1];
        }
    } else {
        var 总行数 = 1;
        for (var i = 0; i < 列数; i++) 总行数 *= 每列元素个数[i];
        var 累计乘积 = 1;
        for (var 列索引 = 0; 列索引 < 列数; 列索引++) {
            累计乘积 *= 每列元素个数[列索引];
            步长数组[列索引] = 总行数 / 累计乘积;
        }
    }
    return 步长数组;
}

/**
 * 构建笛卡尔积矩阵（列优先存储：结果[列][行]）
 * 每一列按照自己的步长循环取源数据
 */
function 构建笛卡尔积矩阵(源数据, 每列元素个数, 步长数组, 结果行数) {
    var 列数 = 每列元素个数.length;
    var 结果 = [];

    for (var 列索引 = 0; 列索引 < 列数; 列索引++) {
        结果[列索引] = [];
        var 该列元素数 = 每列元素个数[列索引];
        var 该列步长 = 步长数组[列索引];

        for (var 行索引 = 0; 行索引 < 结果行数; 行索引++) {
            // 核心公式：源行号 = 循环索引( 向上取整(行号/步长), 元素数 )
            var 源行号 = 循环索引(向上取整除法(行索引 + 1, 该列步长), 该列元素数);
            结果[列索引][行索引] = 源数据[源行号 - 1][列索引];
        }
    }
    return 结果;
}

/**
 * 矩阵转置：列优先 → 行优先
 * 输入: 矩阵[列][行]  (C列 × R行)
 * 输出: 结果[行][列]  (R行 × C列)
 */
function 矩阵转置(矩阵, 列数, 行数) {
    var 结果 = [];
    for (var 行 = 0; 行 < 行数; 行++) {
        结果[行] = [];
        for (var 列 = 0; 列 < 列数; 列++) {
            结果[行][列] = 矩阵[列][行];
        }
    }
    return 结果;
}

/**
 * 按行合并字符串：把每一行的多列值用连接符拼成一个字符串
 */
function 按行合并字符串(矩阵, 列数, 行数, 是否列优先, 连接符) {
    var 结果 = [];
    for (var 行 = 0; 行 < 行数; 行++) {
        var 片段数组 = [];
        for (var 列 = 0; 列 < 列数; 列++) {
            片段数组.push(是否列优先 ? 矩阵[列][行] : 矩阵[行][列]);
        }
        结果[行] = 片段数组.join(连接符);
    }
    return 结果;
}

