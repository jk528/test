function 是否日期格式(格式字符串) {
    if (!格式字符串 || 格式字符串 === 'General' || 格式字符串 === '@') return false;
    var 小写格式 = 格式字符串.toLowerCase();
    var 日期特征字符 = ['y', 'm', 'd', 'h', 's', '年', '月', '日', '时', '分', '秒', '上午', '下午'];
    for (var i = 0; i < 日期特征字符.length; i++) {
        if (小写格式.indexOf(日期特征字符[i]) !== -1) return true;
    }
    return false;
}

function Excel序列号转日期(序列号, 格式字符串) {
    if (序列号 === 0 || 序列号 === null || 序列号 === undefined) return "";

    var 小写格式 = 格式字符串 ? 格式字符串.toLowerCase() : "";

    // 判断是否纯时间格式（含h但不含y和d）
    var 仅时间 = 小写格式.indexOf('h') !== -1
        && 小写格式.indexOf('y') === -1
        && 小写格式.indexOf('d') === -1;

    if (仅时间 || 序列号 < 1) {
        var 总毫秒数 = Math.round(序列号 * 24 * 60 * 60 * 1000);
        var 时 = Math.floor(总毫秒数 / 3600000);
        var 分 = Math.floor((总毫秒数 % 3600000) / 60000);
        var 秒 = Math.floor((总毫秒数 % 60000) / 1000);
        var 毫秒 = 总毫秒数 % 1000;
        var 结果 = 补零两位(时) + ':' + 补零两位(分) + ':' + 补零两位(秒);
        if (小写格式.indexOf('.0') !== -1 || 小写格式.indexOf('.s') !== -1) {
            结果 += '.' + 补零三位(毫秒);
        }
        return 结果;
    }

    // 日期格式（可能含时间）
    var 日期 = new Date((序列号 - 25569) * 86400000);
    var 年 = 日期.getFullYear();
    var 月 = 补零两位(日期.getMonth() + 1);
    var 日 = 补零两位(日期.getDate());
    var 结果 = 年 + '-' + 月 + '-' + 日;

    // 如果格式同时包含日期和时间
    var 含日期 = 小写格式.indexOf('y') !== -1 || 小写格式.indexOf('d') !== -1;
    var 含时间 = 小写格式.indexOf('h') !== -1;
    if (含日期 && 含时间) {
        var 时 = 补零两位(日期.getHours());
        var 分 = 补零两位(日期.getMinutes());
        var 秒 = 补零两位(日期.getSeconds());
        结果 += ' ' + 时 + ':' + 分 + ':' + 秒;
    }

    return 结果;
}

function 补零两位(数字) { return 数字 < 10 ? '0' + 数字 : String(数字); }
function 补零三位(数字) { return 数字 < 10 ? '00' + 数字 : 数字 < 100 ? '0' + 数字 : String(数字); }

/**
 * 批量预处理：把原始值转成可读字符串（处理日期等特殊格式）
 * 返回二维字符串数组
 */
function 预处理数据格式(原始值数组, 原始格式数组, 行数, 列数) {
    var 结果 = [];

    // 先判断每列是否是日期列（整列格式通常一致，只需判断一次）
    var 列是否日期 = [];
    var 列格式字符串 = [];
    for (var 列 = 0; 列 < 列数; 列++) {
        var 格式 = 原始格式数组[0][列];  // 取第一行格式作为列代表
        列是否日期[列] = 是否日期格式(格式);
        列格式字符串[列] = 格式;
    }

    for (var 行 = 0; 行 < 行数; 行++) {
        结果[行] = [];
        for (var 列 = 0; 列 < 列数; 列++) {
            var 值 = 原始值数组[行][列];
            if (值 === null || 值 === undefined || 值 === "") {
                结果[行][列] = "";
            } else if (列是否日期[列] && typeof 值 === 'number') {
                结果[行][列] = Excel序列号转日期(值, 列格式字符串[列]);
            } else {
                结果[行][列] = String(值);
            }
        }
    }
    return 结果;
}

