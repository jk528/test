/**
 * 执行四方循环组合（笛卡尔积）
 * @param {boolean} 是否正向 - true=左慢右快, false=左快右慢
 * @param {boolean} 是否横向输出 - true=列×行, false=行×列
 */
function 执行四方循环(是否正向, 是否横向输出) {
    // 保存并关闭屏幕刷新、自动计算以提升性能
    var 原屏幕刷新状态 = true;
    var 原计算模式 = -4105;  // xlCalculationAutomatic
    try { 原屏幕刷新状态 = Application.ScreenUpdating; Application.ScreenUpdating = false; } catch (e) {}
    try { 原计算模式 = Application.Calculation; Application.Calculation = -4135; } catch (e) {}  // xlCalculationManual

    try {
        var 当前工作表 = Application.ActiveSheet;
        var 总列数 = 获取最后一列(当前工作表);
        if (总列数 <= 0) { 弹窗提示("无有效数据列", 48); return false; }

        // 1. 统计每列有多少个元素
        var 每列元素个数 = [];
        for (var 列 = 0; 列 < 总列数; 列++) {
            var 行数 = 获取最后一行(当前工作表, 列 + 1);
            每列元素个数[列] = 行数 < 1 ? 1 : 行数;
        }

        // 2. 计算笛卡尔积总行数，检查是否超表格限制
        var 结果总行数 = 计算数组乘积(每列元素个数);
        if (结果总行数 > 1048576) { 弹窗提示("已超出表格限制", 48); return false; }

        // 3. 批量读取源数据和单元格格式
        var 原始数据 = 批量读取区域(当前工作表, 1, 1, 结果总行数, 总列数);
        var 原始格式 = 批量读取列格式(当前工作表, 1, 结果总行数);

        // 4. 预处理：日期等特殊格式转字符串
        var 格式化后数据 = 预处理数据格式(原始数据, 原始格式, 结果总行数, 总列数);

        // 5. 计算每列的循环步长
        var 步长数组 = 计算循环步长数组(每列元素个数, 是否正向);

        // 6. 构建笛卡尔积矩阵（列优先存储）
        var 结果矩阵 = 构建笛卡尔积矩阵(格式化后数据, 每列元素个数, 步长数组, 结果总行数);

        // 7. 根据输出方向和合并模式准备最终输出
        var 输出数据, 输出行数, 输出列数;
        var 是否合并 = 当前连接符号 !== "";

        if (是否横向输出) {
            // 横向输出：列 × 行
            if (是否合并) {
                输出数据 = 按行合并字符串(结果矩阵, 总列数, 结果总行数, true, 当前连接符号);
                输出行数 = 1;
                输出列数 = 结果总行数;
            } else {
                输出数据 = 结果矩阵;   // 已经是 [列][行]
                输出行数 = 总列数;
                输出列数 = 结果总行数;
            }
        } else {
            // 竖向输出：行 × 列
            if (是否合并) {
                输出数据 = 按行合并字符串(结果矩阵, 总列数, 结果总行数, true, 当前连接符号);
                输出行数 = 结果总行数;
                输出列数 = 1;
            } else {
                输出数据 = 矩阵转置(结果矩阵, 总列数, 结果总行数);
                输出行数 = 结果总行数;
                输出列数 = 总列数;
            }
        }

        // 8. 写入工作表
        写入结果(当前工作表, "F2", 输出数据, 输出行数, 输出列数, 是否合并);

        return true;
    } catch (e) {
        弹窗提示("执行错误: " + (e.message || String(e)), 48);
        return false;
    } finally {
        try { Application.Calculation = 原计算模式; } catch (e) {}
        try { Application.ScreenUpdating = 原屏幕刷新状态; } catch (e) {}
    }
}

/**
 * 执行双边循环组合（LCM独立循环）
 * @param {boolean} 是否竖向输出 - true=行×列, false=列×行
 */
function 执行双边循环(是否竖向输出) {
    var 原屏幕刷新状态 = true;
    var 原计算模式 = -4105;
    try { 原屏幕刷新状态 = Application.ScreenUpdating; Application.ScreenUpdating = false; } catch (e) {}
    try { 原计算模式 = Application.Calculation; Application.Calculation = -4135; } catch (e) {}

    try {
        var 当前工作表 = Application.ActiveSheet;
        var 总列数 = 获取最后一列(当前工作表);
        if (总列数 <= 0) { 弹窗提示("无有效数据列", 48); return false; }

        // 1. 统计每列元素个数
        var 每列元素个数 = [];
        for (var 列 = 0; 列 < 总列数; 列++) {
            var 行数 = 获取最后一行(当前工作表, 列 + 1);
            每列元素个数[列] = 行数 < 1 ? 1 : 行数;
        }

        // 2. 计算乘积和最小公倍数
        var 列数乘积 = 计算数组乘积(每列元素个数);
        var 最小公倍数 = 计算最小公倍数(每列元素个数);
        if (最小公倍数 > 1048576) { 弹窗提示("已超出表格限制", 48); return false; }

        var 是否完整循环 = (列数乘积 === 最小公倍数);

        // 3. 批量读取源数据和格式
        var 原始数据 = 批量读取区域(当前工作表, 1, 1, 最小公倍数, 总列数);
        var 原始格式 = 批量读取列格式(当前工作表, 1, 最小公倍数);

        // 4. 预处理格式化
        var 格式化后数据 = 预处理数据格式(原始数据, 原始格式, 最小公倍数, 总列数);

        // 5. 构建LCM循环矩阵（列优先）
        var 结果矩阵 = 构建LCM循环矩阵(格式化后数据, 每列元素个数, 最小公倍数);

        // 6. 新建工作表并命名
        var 新工作表 = Application.Worksheets.Add();
        新工作表.Name = 是否完整循环
            ? "完整_" + 最小公倍数 + "sheet" + Application.Sheets.Count
            : "残缺_" + 列数乘积 + "|" + 最小公倍数 + "sheet" + Application.Sheets.Count;

        // 7. 准备输出数据
        var 输出数据, 输出行数, 输出列数;
        var 是否合并 = 当前连接符号 !== "";

        if (是否竖向输出) {
            // 竖向输出：行 × 列
            if (是否合并) {
                输出数据 = 按行合并字符串(结果矩阵, 总列数, 最小公倍数, true, 当前连接符号);
                输出行数 = 最小公倍数;
                输出列数 = 1;
            } else {
                输出数据 = 矩阵转置(结果矩阵, 总列数, 最小公倍数);
                输出行数 = 最小公倍数;
                输出列数 = 总列数;
            }
        } else {
            // 横向输出：列 × 行
            if (是否合并) {
                输出数据 = 按行合并字符串(结果矩阵, 总列数, 最小公倍数, true, 当前连接符号);
                输出行数 = 1;
                输出列数 = 最小公倍数;
            } else {
                输出数据 = 结果矩阵;
                输出行数 = 总列数;
                输出列数 = 最小公倍数;
            }
        }

        // 8. 写入结果
        写入结果(新工作表, "A1", 输出数据, 输出行数, 输出列数, 是否合并);

        return true;
    } catch (e) {
        弹窗提示("执行错误: " + (e.message || String(e)), 48);
        return false;
    } finally {
        try { Application.Calculation = 原计算模式; } catch (e) {}
        try { Application.ScreenUpdating = 原屏幕刷新状态; } catch (e) {}
    }
}

